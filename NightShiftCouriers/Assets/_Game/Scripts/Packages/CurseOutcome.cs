// What can happen when someone opens a cursed package (plan 4.9).
public enum CurseOutcome
{
    RareItem,        // good: an item falls out
    BigMoney,        // good: cash inside
    LoreReveal,      // good: a journal entry
    MonsterReleased, // bad: something climbs out
    FloodJump,       // bad: the water rises early
    Screaming        // bad: the package starts screaming (a noise source) and is worthless
}
